-- Server-side record of orders blocked by trading locks. The card reads
-- today's rows (user timezone) so "Blocked today" includes enforcement that
-- happened outside this device. Inserts are made with the service role from
-- api/ctrader/trade.ts; users may only read/insert their own rows.

create table if not exists public.lock_blocks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  portfolio_id text not null,
  rule text not null,
  created_at timestamptz not null default now()
);

create index if not exists lock_blocks_user_portfolio_created_idx
  on public.lock_blocks (user_id, portfolio_id, created_at desc);

alter table public.lock_blocks enable row level security;

drop policy if exists "lock_blocks_owner_select" on public.lock_blocks;
create policy "lock_blocks_owner_select" on public.lock_blocks
  for select using (auth.uid() = user_id);

drop policy if exists "lock_blocks_owner_insert" on public.lock_blocks;
create policy "lock_blocks_owner_insert" on public.lock_blocks
  for insert with check (auth.uid() = user_id);
